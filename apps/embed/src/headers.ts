// Response headers for the embed page. Any site may frame it (that's the
// point), so frame-ancestors is open; everything else is locked to what the
// viewer needs: the Supabase REST API and the scan assets.

const origin = (url: string) => new URL(url).origin;

export function embedHeaders(env: { supabaseUrl: string; assetsBaseUrl: string }): Record<string, string> {
  const connect = [...new Set(["'self'", origin(env.supabaseUrl), origin(env.assetsBaseUrl)])].join(" ");
  const csp = [
    "default-src 'self'",
    "frame-ancestors *",
    "script-src 'self'",
    // The page's own inline <style>; PlayCanvas sets inline styles on the canvas.
    "style-src 'self' 'unsafe-inline'",
    `connect-src ${connect}`,
    // SOG textures decode from blobs; the splat sorter runs in a blob worker.
    "img-src 'self' data: blob:",
    "worker-src 'self' blob:",
    "base-uri 'none'",
    "form-action 'none'",
    "object-src 'none'",
  ].join("; ");
  return {
    "Content-Security-Policy": csp,
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
  };
}

/** Cloudflare Pages `_headers` file for the built site. */
export function headersFile(headers: Record<string, string>): string {
  const lines = ["# Generated by vite.config.ts from .env; do not edit.", "/*"];
  for (const [name, value] of Object.entries(headers)) lines.push(`  ${name}: ${value}`);
  lines.push("/assets/*", "  Cache-Control: public, max-age=31536000, immutable");
  return `${lines.join("\n")}\n`;
}
